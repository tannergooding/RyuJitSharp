    private ValueNum CombineRelatedRelops(var_types type, VNFunc func, ValueNum arg0VN, ValueNum arg1VN)
    {
        var first = new VNFuncApp();
        if (!GetVNFunc(arg0VN, ref first) || !VNFuncIsComparison(first.Func) ||
            varTypeIsFloating(TypeOfVN(first.GetArg(0))))
        {
            return NoVN;
        }

        var second = new VNFuncApp();
        if (!GetVNFunc(arg1VN, ref second) || !VNFuncIsComparison(second.Func) ||
            (first.GetArg(0) != second.GetArg(0)) || (first.GetArg(1) != second.GetArg(1)))
        {
            return NoVN;
        }

        var isAnd = func == VNF_AND;
        var relop0Table = isAnd ? s_relatedRelopTable_AND_Relop0 : s_relatedRelopTable_OR_Relop0;
        var relop1Table = isAnd ? s_relatedRelopTable_AND_Relop1 : s_relatedRelopTable_OR_Relop1;
        var constantFlags = s_relatedRelopFlags;
        var jointRelopTable = isAnd ? s_relatedRelopTable_AND_JointRelop : s_relatedRelopTable_OR_JointRelop;

        for (var i = 0; i < relop0Table.Length; i++)
        {
            if (((relop0Table[i] == first.Func) && (relop1Table[i] == second.Func)) ||
                ((relop0Table[i] == second.Func) && (relop1Table[i] == first.Func)))
            {
                var flags = constantFlags[i];
                if (isAnd && ((flags & RelatedRelopFlags.AndProducesZero) != 0))
                {
                    return VNZeroForType(type);
                }

                if (!isAnd && ((flags & RelatedRelopFlags.OrProducesOne) != 0))
                {
                    return VNOneForType(type);
                }

                return VNForFunc(type, jointRelopTable[i], first.GetArg(0), first.GetArg(1));
            }
        }

        return NoVN;
    }
